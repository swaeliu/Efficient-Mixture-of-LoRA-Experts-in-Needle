#!/usr/bin/env python
"""Phase 4C — controlled synthetic sequence task with latent transition processes.

K latent processes share one vocabulary of V tokens; each process k is a
first-order Markov chain with its own (peaked) transition matrix. A sequence is
generated by one process; the process id is NEVER given to the model, it must
be inferred from the tokens seen so far.

* Pretraining distribution: processes P_1..P_K.
* Adaptation distribution: shifted processes P'_k = (1 - eps) P_k + eps Q_k with
  process-specific random shifts Q_k, so the adapters have to learn an
  input-dependent (process-dependent) correction to the frozen backbone.

Diagnostics: the conditional entropy rate of each process family (the CE a
model knowing the process and the true previous token would achieve) is the
oracle lower bound for next-token cross-entropy.
"""
from __future__ import annotations

import numpy as np


def _peaked_rows(rng, V, n_hot, hot_mass):
    """Each row puts `hot_mass` on `n_hot` random tokens and spreads the rest uniformly."""
    P = np.full((V, V), (1 - hot_mass) / (V - n_hot))
    for i in range(V):
        hot = rng.choice(V, n_hot, replace=False)
        P[i, hot] = hot_mass / n_hot * (0.7 + 0.6 * rng.random(n_hot))
        P[i] /= P[i].sum()
    return P


def make_processes(cfg: dict, seed: int) -> dict:
    d = cfg["data"]
    rng = np.random.default_rng(seed)
    V, K = d["vocab_size"], d["n_processes"]
    P = [_peaked_rows(rng, V, d["n_hot"], d["hot_mass"]) for _ in range(K)]
    Q = [_peaked_rows(rng, V, d["n_hot"], d["hot_mass"]) for _ in range(K)]
    eps = d["shift_eps"]
    P_shift = [(1 - eps) * p + eps * q for p, q in zip(P, Q)]
    return {"pretrain": P, "adapt": P_shift, "shift_eps": eps, "V": V, "K": K}


def sample_sequences(matrices: list[np.ndarray], n: int, T: int, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """n sequences of length T+1 (inputs = [:, :-1], targets = [:, 1:]); returns (tokens, process ids)."""
    K = len(matrices)
    V = matrices[0].shape[0]
    assert n % K == 0
    z = rng.permutation(np.repeat(np.arange(K), n // K))
    toks = np.zeros((n, T + 1), dtype=np.int64)
    toks[:, 0] = rng.integers(0, V, n)
    cum = [np.cumsum(m, axis=1) for m in matrices]
    u = rng.random((n, T))
    for t in range(T):
        for k in range(K):
            idx = z == k
            rows = cum[k][toks[idx, t]]
            toks[idx, t + 1] = (u[idx, t][:, None] > rows).sum(1)
    toks = np.minimum(toks, V - 1)
    return toks, z


def make_splits(cfg: dict, processes: dict, seed: int, family: str) -> dict:
    d = cfg["data"]
    rng = np.random.default_rng(seed)
    mats = processes[family]
    out = {}
    for split, n in (("train", d["n_train"]), ("val", d["n_val"]), ("test", d["n_test"])):
        toks, z = sample_sequences(mats, n, d["seq_len"], rng)
        out[split] = {"x": toks[:, :-1], "y": toks[:, 1:], "z": z}
    return out


def entropy_rate(matrices: list[np.ndarray], split: dict) -> float:
    """Average next-token cross-entropy (nats) of the TRUE process given the true previous token."""
    x, y, z = split["x"], split["y"], split["z"]
    total = 0.0
    for k, m in enumerate(matrices):
        idx = z == k
        total += -np.log(m[x[idx], y[idx]]).sum()
    return float(total / y.size)


def oracle_accuracy(matrices: list[np.ndarray], split: dict) -> float:
    x, y, z = split["x"], split["y"], split["z"]
    correct = 0
    for k, m in enumerate(matrices):
        idx = z == k
        correct += (m[x[idx]].argmax(-1) == y[idx]).sum()
    return float(correct / y.size)


def process_identifiability(processes: dict, split: dict, family: str) -> float:
    """Accuracy of the Bayes-optimal process classifier given the whole sequence (diagnostic)."""
    mats = processes[family]
    x, y, z = split["x"], split["y"], split["z"]
    ll = np.stack([np.log(m[x, y]).sum(1) for m in mats], axis=1)
    return float((ll.argmax(1) == z).mean())
